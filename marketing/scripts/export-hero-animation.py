#!/usr/bin/env python3
"""Export the homepage hero (the live sidebar demo) as one standalone HTML file: brand/hero-animation.html.

    python3 scripts/export-hero-animation.py

The markup, styles and script are cut out of pluckr.webflow/index.html, so rerun this after the hero changes.
Differences from the homepage:
  - The sidebar is NOT absolutely positioned. It sits in normal flow inside a slot that is sized to the scaled sidebar,
    and the stage centres the slot with grid. Only the pointer is an overlay (it has to float over the sidebar).
  - Photos, icons and the font are embedded, so the file works on its own.
"""
import base64
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "webflow"
src = (SITE / "index.html").read_text()


def between(text, start, end, include_end=False):
    a = text.index(start)
    b = text.index(end, a)
    return text[a : b + (len(end) if include_end else 0)]


def data_uri(path, mime):
    return f"data:{mime};base64," + base64.b64encode(path.read_bytes()).decode()


# ---- markup -------------------------------------------------------------------------------------------------------
sidebar = between(src, '<div class="sidebar-wrap" id="wrap">', '<div class="cursor" id="cursor"').rstrip()
cursor = between(src, '<div class="cursor" id="cursor"', "</svg>\n      </div>", include_end=True)

# The sidebar sits in a slot that takes the scaled size, so it never needs position: absolute.
sidebar = sidebar.replace('<div class="sidebar-wrap" id="wrap">', '<div class="sidebar-slot"><div class="sidebar-wrap" id="wrap">', 1)
sidebar += "\n      </div>"  # closes the slot

mimes = {".jpg": "image/jpeg", ".svg": "image/svg+xml"}
for path in sorted((SITE / "images" / "v2").iterdir()):
    if path.suffix in mimes:
        sidebar = sidebar.replace(f'src="images/v2/{path.name}"', f'src="{data_uri(path, mimes[path.suffix])}"')
assert "images/v2/" not in sidebar, "an image path was left behind"

# ---- styles -------------------------------------------------------------------------------------------------------
inner_css = between(src, ".hero3 .sidebar {", ".hero3 .cursor svg {")
inner_css += src[src.index(".hero3 .cursor svg {") : src.index("\n", src.index(".hero3 .cursor svg {"))]
resets = "\n".join(
    line.strip()
    for line in between(src, ".hero3 *, .hero3 *::before", ".hero3 a { text-decoration: none; }", include_end=True).splitlines()
    if line.strip()
)
variables = between(src, "--black: #000;", "color: var(--white);")

# ---- script -------------------------------------------------------------------------------------------------------
js_start = src.rindex("(function () {", 0, src.index("var root = document.querySelector('.hero3');"))
js_end = src.index("})();\n  </script>", js_start) + len("})();")
script = src[js_start:js_end]
assert "getBoundingClientRect" in script and "IntersectionObserver" in script

font = data_uri(SITE / "fonts" / "PPNeueMontreal-Medium.ttf", "font/ttf")

html = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Pluckr hero animation</title>
<!--
  The Pluckr sidebar demo, as on the homepage. One file: styles, markup, script, photos and font are all inside.
  Photos: Ben Jessop, Gavin Allanwood and Elina Ayupova on Unsplash.
  Generated by scripts/export-hero-animation.py from pluckr.webflow/index.html. Edit the homepage, then regenerate.
-->
<style>
@font-face {{ font-family: "PP Neue Montreal"; src: url({font}) format("truetype"); font-weight: 500; font-style: normal; font-display: swap; }}
* {{ box-sizing: border-box; }}
html, body {{ margin: 0; background: #000; }}
body {{ display: grid; grid-template-rows: 1fr auto; min-height: 100vh; min-height: 100svh; }}

/* The scene: a dark stage with the sidebar centred in it. */
.hero3 {{
  display: grid;
  min-height: 0;
  {variables.strip()}
  color: var(--white);
  font-family: "PP Neue Montreal", "Helvetica Neue", Arial, sans-serif;
  font-weight: 500;
  font-synthesis: none;
  -webkit-font-smoothing: antialiased;
  text-rendering: optimizeLegibility;
}}
.hero3 .stage {{ position: relative; display: grid; place-items: center; min-height: 0; overflow: hidden; background: #0a0a0a; --s: 0.9; }}

/* The homepage gets these from the site's base stylesheet; this file has none. */
.hero3 p, .hero3 h1 {{ margin: 0; }}
.hero3 button {{ margin: 0; padding: 0; border: 0; border-radius: 0; background: none; color: inherit; font: inherit; line-height: inherit; text-align: inherit; cursor: default; -webkit-appearance: none; appearance: none; }}

/* No absolute positioning: the slot takes the size of the scaled sidebar, so the grid can centre it. */
.hero3 .sidebar-slot {{ width: calc(300px * var(--s)); height: calc(740px * var(--s)); }}
.hero3 .sidebar-wrap {{ width: 300px; height: 740px; transform: scale(var(--s)); transform-origin: top left; }}

{inner_css}
{resets}

.credit {{ margin: 0; padding: 14px 24px; color: rgba(255, 255, 255, 0.58); font: 500 12px/1.4 "Helvetica Neue", Arial, sans-serif; text-align: center; }}
.credit a {{ color: inherit; text-decoration: underline; }}
</style>
</head>
<body>
  <section class="hero3" aria-label="Pluckr">
    <div class="stage" id="stage" role="group" aria-label="Pluckr sidebar, shown working on a Google Doc">
      {sidebar}

      {cursor}
    </div>
  </section>
  <p class="credit">Photos by Ben Jessop, Gavin Allanwood and Elina Ayupova on <a href="https://unsplash.com">Unsplash</a>.</p>
<script>
{script}
</script>
</body>
</html>
"""

out = ROOT / "brand" / "hero-animation.html"
out.write_text(html)
print(f"wrote {out} ({len(html) / 1024:.0f} KB)")
